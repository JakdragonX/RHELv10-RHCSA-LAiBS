CONCEPTUAL UNDERSTANDING
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

/proc is Not a Real Filesystem:
  Files in /proc have no inode on disk. Reading them triggers the kernel to
  generate output from in-memory data structures. Writing to /proc/sys files
  modifies kernel variables in memory directly — instantly, without a syscall
  to a daemon or service. This is as close to "talking to the kernel" as you
  can get from userspace without writing a kernel module.

sysctl.d Load Priority:
  /usr/lib/sysctl.d/   → package defaults (lowest priority)
  /run/sysctl.d/       → runtime overrides (ephemeral)
  /etc/sysctl.d/       → admin overrides (highest priority)
  /etc/sysctl.conf     → legacy single-file location (still works)

  Within each directory, files load alphabetically. Name your files with a
  numeric prefix (e.g., 90-router.conf) to control precedence explicitly.

Why net.ipv4.ip_forward Matters:
  By default, Linux drops packets not addressed to itself — it behaves as a
  host, not a router. Setting ip_forward=1 tells the kernel to forward packets
  between interfaces, which is required for NAT, routing, and container
  networking (Docker and Podman depend on this).


COMMON MISTAKES & TROUBLESHOOTING
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Mistake 1: Writing to /proc/sys but forgetting the sysctl.d file
  Result: Change works until next reboot, then disappears
  Fix: Always pair runtime changes with a sysctl.d config file

Mistake 2: Editing /usr/lib/sysctl.d/ files directly
  Result: Changes get overwritten on next package update
  Fix: Always put overrides in /etc/sysctl.d/

Mistake 3: Using sysctl -p with no filename after adding a new file
  Result: Only reads /etc/sysctl.conf (legacy), misses your new file
  Fix: sysctl -p /etc/sysctl.d/yourfile.conf, or sysctl --system for all files


