prerequisites() {
    cat << 'EOF'
Knowledge Requirements:
  • That /proc is a pseudo-filesystem — it has no backing disk storage;
    its files are generated by the kernel on-read and written directly to
    kernel memory structures on-write
  • The difference between reading kernel state (/proc status files) and
    changing it (/proc/sys tunables)
  • That sysctl parameter names map directly to paths under /proc/sys/,
    with dots replacing slashes (e.g., net.ipv4.ip_forward = /proc/sys/net/ipv4/ip_forward)

Commands You'll Use:
  • cat / echo      - Read and write /proc files directly
  • sysctl -a       - List all tunable kernel parameters and current values
  • sysctl -w       - Write a tunable value (runtime, not persistent)
  • sysctl -p       - Apply settings from a sysctl.d config file
  • sysctl --system - Apply all settings from all sysctl.d config files

Files You'll Interact With:
  • /proc/                     - Kernel interface pseudo-filesystem
  • /proc/sys/                 - Tunable kernel parameters
  • /proc/meminfo              - Memory segment details
  • /proc/cpuinfo              - CPU details
  • /etc/sysctl.d/             - Drop-in directory for persistent sysctl settings
  • /usr/lib/sysctl.d/         - Package-provided sysctl defaults (do not edit)

KEY CONCEPT — /proc/sys and sysctl name mapping:
  /proc/sys/net/ipv4/ip_forward   ←→   net.ipv4.ip_forward
  /proc/sys/vm/swappiness         ←→   vm.swappiness
  /proc/sys/kernel/hostname       ←→   kernel.hostname

  The path separator '/' becomes '.' in sysctl notation.
  Both representations refer to the same kernel value.
EOF
}

