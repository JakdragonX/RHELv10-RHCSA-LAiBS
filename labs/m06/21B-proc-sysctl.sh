SOLUTION:
─────────
Commands:
  echo 'net.ipv4.ip_forward = 1' > /etc/sysctl.d/lab21b.conf
  sysctl -p /etc/sysctl.d/lab21b.conf
  sysctl net.ipv4.ip_forward

Explanation:
  • /etc/sysctl.d/<name>.conf: drop-in directory for persistent sysctl settings.
    Files here are read and applied at boot by systemd-sysctl.service.
    The counterpart /usr/lib/sysctl.d/ holds package-provided defaults — do not
    edit those files; put overrides in /etc/sysctl.d/ instead.
  • File format: one setting per line as 'parameter = value'. Comments use #.
  • sysctl -p <file>: reads and immediately applies the specified file.
    Without a filename, -p reads /etc/sysctl.conf (legacy location).
  • sysctl --system: applies ALL sysctl.d files in order (useful for confirming
    the full set of settings that will be applied at boot).

Load order when multiple files exist:
  Files are applied alphabetically by filename. A file named 99-custom.conf
  will override settings from 10-default.conf for the same parameter.
  /etc/sysctl.d/ takes priority over /usr/lib/sysctl.d/ for the same filename.

Verification:
