━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

1. Runtime change: sysctl -w parameter=value  (or echo value > /proc/sys/path)
