Key observations:
  • /proc/meminfo: MemTotal, MemFree, Cached, SwapTotal, etc. — these are the
    same values tools like 'free' and 'top' read from.
  • /proc/cpuinfo: one block per logical CPU. Fields like 'model name',
    'cpu MHz', 'flags' (supported instruction sets), and 'cpu cores'.
  • /proc/version: kernel version string, gcc version used to compile it,
    and the build timestamp.
  • sysctl -a: hundreds of parameters across namespaces: kernel.*, net.*, vm.*,
    fs.*, dev.*. These are all the knobs available without recompiling the kernel.

Why this matters:
  Many performance and monitoring tools (vmstat, free, ss, netstat) are simply
  formatted readers of /proc files. Understanding /proc lets you go directly
  to the source when a tool isn't available.

